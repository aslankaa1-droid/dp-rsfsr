# -*- coding: utf-8 -*-
"""Сборка единого свода показателей (_Мастер/Единые_показатели_v2.md) из движка."""

import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import model as M  # noqa: E402
from собрать_документ import n, pct, dt, row, head  # noqa: E402

ROOT = os.path.dirname(os.path.abspath(__file__))
DOC = os.path.abspath(os.path.join(ROOT, "..", "..", "_Мастер", "Единые_показатели_v2.md"))


def main():
    a = M.load()
    base = M.build(a)
    if M.selfcheck(base):
        raise SystemExit("модель не сходится")
    scen = {k: {"доля": v["доля_год10"], "вес": v["вес"],
                "модель": M.build(a, share_year10=v["доля_год10"])}
            for k, v in a["сценарии"].items()}
    exp_ev = sum(v["вес"] * v["модель"]["EV"] for v in scen.values())
    mc = M.monte_carlo(a)
    tri = M.triangulate(a, base["EV"])
    deal = M.deal_terms(a, tri["pre_money_млн_usd"])
    iv = M.investor_metrics(a, base, deal["доля_инвестора"], int(a["раунд"].get("год_выхода", 7)))
    dm1 = M.build(a, delay=1)
    mk = a["макро"]
    yy = base["годы"]
    fx = mk["FX_USD_RUB"]

    L = []
    w = L.append
    w("# Единые показатели проекта · v5 (%s)" % dt(a["дата_модели"]))
    w("")
    w("Единый источник значений для всех документов проекта. Любая цифра в бизнес-плане, "
      "отчёте об оценке, презентациях и на сайте должна совпадать с этим сводом.")
    w("")
    w("> **Свод собирается программно** из `03_Финансовая_модель/Модель/assumptions.json` "
      "скриптом `собрать_SoT.py`. Править цифры здесь вручную нельзя.")
    w("")
    w("**Что изменилось v4 → v5.** Финансовая модель пересчитана заново: итог выручки "
      "приведён к сумме строк, транзитные услуги оценщиков и страховщиков выведены из "
      "выручки, ставка налога на прибыль поднята с 20% до 25%, учтён перенос убытков, "
      "фонд оплаты труда выведен из численности и оклада, горизонт сдвинут на 2027–2036 "
      "годы, терминальная стоимость считается одним методом, скидка за стадию применяется "
      "один раз. Подробности — раздел «Что изменилось» в финансовой модели.")
    w("")
    w("---")
    w("")
    w("## 1. Макроэкономическая база")
    w("")
    w(head(["Параметр", "Значение", "Дата"], ["---", "---:", "---"]))
    w(row(["Ключевая ставка Банка России", pct(mk["ключевая_ставка_ЦБ"], 2), dt(mk["дата_ключевой_ставки"])]))
    w(row(["Доходность 10-летних ОФЗ", pct(mk["ОФЗ_10Y"], 2), dt(mk["дата_ОФЗ"])]))
    w(row(["Премия за рыночный риск (ERP)", pct(mk["ERP_РФ"], 2), "Damodaran"]))
    w(row(["Бета (финансовые услуги)", ("%.2f" % mk["beta_financial_services"]).replace(".", ","), "Damodaran"]))
    w(row(["Курс USD/RUB", n(fx, 2) + " ₽", dt(mk["дата_FX"])]))
    w(row(["Целевая инфляция", pct(mk["инфляция_таргет"], 0), "ориентир Банка России"]))
    w(row(["**Ставка дисконтирования (WACC)**", "**" + pct(base["WACC"], 2) + "**", "расчёт"]))
    w("")
    w("> Блок зафиксирован на май 2026 года. Перед переговорами обновить.")
    w("")
    w("## 2. Операционные показатели, млн ₽")
    w("")
    w(head(["Год"] + [str(y) for y in yy], ["---"] + ["---:"] * len(yy)))
    w(row(["Выручка"] + [n(x) for x in base["выручка"]]))
    w(row(["Операционные расходы"] + [n(x) for x in base["opex_всего"]]))
    w(row(["EBITDA"] + [n(x) for x in base["EBITDA"]]))
    w(row(["Капитальные вложения"] + [n(x) for x in base["CapEx"]]))
    w(row(["Свободный денежный поток"] + [n(x) for x in base["FCF"]]))
    w("")
    w("Сумма свободного денежного потока за горизонт — **%s млн ₽**. Капитальные вложения "
      "за горизонт — **%s млн ₽**." % (n(sum(base["FCF"])), n(base["CapEx_всего_млн"])))
    w("")
    w("## 3. Оценка")
    w("")
    w(head(["Показатель", "Значение"], ["---", "---:"]))
    w(row(["Сумма дисконтированных потоков", n(base["PV_FCF_сумма"]) + " млн ₽"]))
    w(row(["Дисконтированная терминальная стоимость", n(base["PV_TV"]) + " млн ₽"]))
    w(row(["Доля терминальной стоимости", pct(base["доля_TV_в_EV"], 0)]))
    w(row(["**Стоимость бизнеса (EV), базовый сценарий**",
           "**" + ("%.1f" % (base["EV"] / 1000)).replace(".", ",") + " млрд ₽**"]))
    w(row(["Внутренняя норма доходности проекта", pct(base["IRR_проекта"], 1)]))
    w(row(["Окупаемость простая", ("%.2f" % base["окупаемость_простая_лет"]).replace(".", ",") + " года"]))
    w(row(["Окупаемость дисконтированная",
           ("%.2f" % base["окупаемость_дисконтированная_лет"]).replace(".", ",") + " года"]))
    w(row(["Пиковая потребность в финансировании", n(base["пиковая_потребность_млн"]) + " млн ₽"]))
    w("")
    w("> Внутренняя норма доходности проекта выше 100% — следствие того, что модель не "
      "отражает полной стоимости входа на рынок. В переговорах опираться на стоимость "
      "бизнеса и расчёт для инвестора, а не на этот показатель.")
    w("")
    w("## 4. Сценарии")
    w("")
    w(head(["Сценарий", "Доля рынка год 10", "Вес", "Стоимость бизнеса, млрд ₽"],
           ["---", "---:", "---:", "---:"]))
    for k in ["Консервативный", "Базовый", "Оптимистичный"]:
        d = scen[k]
        w(row([k, pct(d["доля"], 0), pct(d["вес"], 0),
               ("%.1f" % (d["модель"]["EV"] / 1000)).replace(".", ",")]))
    w(row(["**Ожидаемое значение**", "—", "100%",
           "**" + ("%.1f" % (exp_ev / 1000)).replace(".", ",") + "**"]))
    w("")
    w("### Имитационное моделирование")
    w("")
    w("%d итераций, зерно %d. Варьируются доля рынка, ставка дисконтирования, расходы и "
      "задержка запуска." % (mc["итераций"], mc["зерно"]))
    w("")
    w(head(["Перцентиль", "P5", "P10", "P25", "Медиана", "P75", "P90", "P95"],
           ["---", "---:", "---:", "---:", "---:", "---:", "---:", "---:"]))
    w(row(["Стоимость бизнеса, млрд ₽"] +
          [("%.1f" % (mc[k] / 1000)).replace(".", ",")
           for k in ["P5", "P10", "P25", "медиана", "P75", "P90", "P95"]]))
    w("")
    w("Вероятность стоимости выше 50 млрд ₽ — %s; вероятность отрицательной "
      "стоимости — %s. Медиана имитации ниже базового сценария, потому что имитация "
      "учитывает вероятность задержки запуска."
      % (pct(mc["доля_выше_50млрд"], 1), pct(mc["доля_ниже_нуля"], 1)))
    w("")
    w("## 5. Стоимость входа и структура раунда")
    w("")
    w(head(["Показатель", "USD", "RUB"], ["---", "---:", "---:"]))
    w(row(["Pre-money", "$" + n(deal["pre_money_млн_usd"]) + " млн",
           ("%.2f" % deal["pre_money_млрд_руб"]).replace(".", ",") + " млрд ₽"]))
    w(row(["Раунд", "$" + n(deal["раунд_млн_usd"]) + " млн", n(deal["раунд_млн_руб"]) + " млн ₽"]))
    w(row(["Post-money", "$" + n(deal["post_money_млн_usd"]) + " млн",
           ("%.2f" % deal["post_money_млрд_руб"]).replace(".", ",") + " млрд ₽"]))
    w(row(["Доля инвестора", pct(deal["доля_инвестора"], 2), pct(deal["доля_инвестора"], 2)]))
    w("")
    w("Скидка за стадию %s применена один раз и только к доходному и сравнительному "
      "подходам. В редакции v4 она применялась дважды, из-за чего стоимость входа была "
      "занижена примерно вдвое ($100 млн против $%s млн)."
      % (pct(tri["stage_discount"], 0), n(deal["pre_money_млн_usd"])))
    w("")
    w("**Заявленного раунда не хватает:** пик потребности %s млн ₽ против раунда %s млн ₽. "
      "Рекомендуемый размер — около %s млрд ₽. При задержке запуска на год потребность "
      "составит %s млн ₽."
      % (n(base["пиковая_потребность_млн"]), n(deal["раунд_млн_руб"]),
         ("%.1f" % (base["пиковая_потребность_млн"] * 1.05 / 1000)).replace(".", ","),
         n(dm1["пиковая_потребность_млн"])))
    w("")
    w("## 6. Расчёт для инвестора")
    w("")
    w(head(["Показатель", "Значение"], ["---", "---:"]))
    w(row(["Инвестиция", n(iv["инвестиция_млн"]) + " млн ₽"]))
    w(row(["Доля", pct(iv["доля"], 2)]))
    w(row(["Горизонт", "%d лет, выход в %d году" % (iv["срок_лет"], iv["год_выхода"])]))
    w(row(["Кратность возврата", ("%.1f" % iv["кратность"]).replace(".", ",") + "×"]))
    w(row(["Внутренняя норма доходности инвестора", pct(iv["IRR_инвестора"], 1)]))
    w("")
    w("Показатели предполагают полное выполнение плана; это верхняя граница, а не ожидание.")
    w("")
    w("## 7. Что запрещено делать с этими цифрами")
    w("")
    w("1. Приводить показатель, которого нет в этом своде.")
    w("2. Смешивать уровень проекта и уровень инвестора — это разные оси.")
    w("3. Показывать валовые сборы как выручку платформы.")
    w("4. Применять скидку за стадию повторно.")
    w("5. Публиковать оценку без оговорки, что нормативная база не принята, а траектория "
      "доли рынка ничем не подтверждена.")
    w("")
    w("---")
    w("")
    w("**Свод v5 · %s · собран программно из расчётного движка.**" % dt(a["дата_модели"]))
    w("")

    io.open(DOC, "w", encoding="utf-8").write("\n".join(L))
    sys.stdout.write("Записано: %s\n" % DOC)


if __name__ == "__main__":
    main()
