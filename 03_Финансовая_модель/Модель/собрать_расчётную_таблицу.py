# -*- coding: utf-8 -*-
"""Сборка расчётной таблицы отчёта об оценке (DPFSR.RU_PRICE/Расчёты/) из движка."""

import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import model as M  # noqa: E402
from собрать_документ import dt  # noqa: E402

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(ROOT, "..", "..", "DPFSR.RU_PRICE", "Расчёты",
                                   "Расчётная_таблица_ЦПФСР.csv"))


def f(x, d=2):
    return ("%.*f" % (d, x)).replace(".", ",")


def main():
    a = M.load()
    b = M.build(a)
    if M.selfcheck(b):
        raise SystemExit("модель не сходится")
    mk = a["макро"]
    fx = mk["FX_USD_RUB"]
    tri = M.triangulate(a, b["EV"])
    deal = M.deal_terms(a, tri["pre_money_млн_usd"])
    mc = M.monte_carlo(a)
    scen = {k: M.build(a, share_year10=v["доля_год10"]) for k, v in a["сценарии"].items()}

    L = []
    w = L.append
    w("Расчётная таблица к отчёту об оценке ЦПФСР;редакция 2;%s;;;;;" % dt(a["дата_модели"]))
    w("Источник значений;03_Финансовая_модель/Модель/assumptions.json;собрано программно;;;;;")
    w(";;;;;;;")

    w("Параметр;Источник;Значение;Единица;Дата актуальности")
    w("Ключевая ставка Банка России;cbr.ru;%s;%%;%s" % (f(mk["ключевая_ставка_ЦБ"] * 100), dt(mk["дата_ключевой_ставки"])))
    w("Доходность 10Y ОФЗ;рыночные данные;%s;%%;%s" % (f(mk["ОФЗ_10Y"] * 100), dt(mk["дата_ОФЗ"])))
    w("USD/RUB официальный;cbr.ru;%s;RUB/USD;%s" % (f(fx, 4), dt(mk["дата_FX"])))
    w("Премия за рыночный риск (ERP);Damodaran;%s;%%;январь 2026" % f(mk["ERP_РФ"] * 100))
    w("Бета (финансовые услуги);Damodaran;%s;-;январь 2026" % f(mk["beta_financial_services"]))
    w("Премия за стадию;IPEV;%s;%%;%s" % (f(mk["премия_за_стадию"] * 100), dt(a["дата_модели"])))
    w("Премия за неликвидность;IPEV;%s;%%;%s" % (f(mk["премия_за_неликвидность"] * 100), dt(a["дата_модели"])))
    w("Ставка дисконтирования;расчёт;%s;%%;%s" % (f(b["WACC"] * 100), dt(a["дата_модели"])))
    w("Налог на прибыль;176-ФЗ от 12.07.2024;%s;%%;с 01.01.2025" % f(a["налоги"]["налог_на_прибыль"] * 100, 0))
    w(";;;;;;;")

    w("Базовый сценарий;Год;Выручка_млрд_руб;Расходы_млрд_руб;EBITDA_млрд_руб;EBITDA_маржа;CapEx_млрд_руб;Поток_млрд_руб")
    for i, y in enumerate(b["годы"]):
        m = b["EBITDA_маржа"][i]
        w("Base;%d;%s;%s;%s;%s;%s;%s" % (
            y, f(b["выручка"][i] / 1000), f(b["opex_всего"][i] / 1000),
            f(b["EBITDA"][i] / 1000), (f(m * 100, 1) + "%") if m is not None else "-",
            f(b["CapEx"][i] / 1000), f(b["FCF"][i] / 1000)))
    w("Сумма потока %d-%d;;;;;;;%s" % (b["годы"][0], b["годы"][-1], f(sum(b["FCF"]) / 1000)))
    w(";;;;;;;")

    w("Дисконтирование;Год;t;Поток_млрд_руб;Дисконт-фактор;Дисконтированный_поток_млрд_руб")
    for i, y in enumerate(b["годы"]):
        w(";%d;%d;%s;%s;%s" % (y, i + 1, f(b["FCF"][i] / 1000),
                               f(b["дисконт_факторы"][i], 4), f(b["PV_FCF"][i] / 1000)))
    w("Сумма дисконтированных потоков;;;;;%s" % f(b["PV_FCF_сумма"] / 1000))
    w(";;;;;;;")

    w("Терминальная стоимость;Метод;Гордон на нормализованном потоке;g;%s;;;" % (f(a["терминальная_стоимость"]["темп_роста_g"] * 100, 0) + "%"))
    w(";Нормализованный поток, млрд руб;%s;;;;;" % f(b["FCF_нормализованный"] / 1000))
    w(";Терминальная стоимость, млрд руб;%s;;;;;" % f(b["TV"] / 1000, 1))
    w(";Дисконтированная, млрд руб;%s;;;;;" % f(b["PV_TV"] / 1000))
    w(";Доля в стоимости бизнеса;%s;;;;;" % (f(b["доля_TV_в_EV"] * 100, 0) + "%"))
    w(";;;;;;;")

    w("Стоимость бизнеса;млрд руб;%s;млн USD;%s;;;" % (f(b["EV"] / 1000), f(b["EV"] / fx, 0)))
    w("Внутренняя норма доходности проекта;%s;;;;;;" % (f(b["IRR_проекта"] * 100, 1) + "%"))
    w("Окупаемость простая;%s;лет;;;;;" % f(b["окупаемость_простая_лет"]))
    w("Окупаемость дисконтированная;%s;лет;;;;;" % f(b["окупаемость_дисконтированная_лет"]))
    w("Пиковая потребность в финансировании;%s;млн руб;;;;;" % f(b["пиковая_потребность_млн"], 0))
    w(";;;;;;;")

    w("Свёртка подходов;Подход;До скидки_млн_USD;Скидка применена;После скидки_млн_USD;Вес;Вклад_млн_USD")
    for r in tri["строки"]:
        w(";%s;%s;%s;%s;%s;%s" % (r["метод"], f(r["до_дисконта_млн_usd"], 0),
                                  "да" if r["дисконт"] else "нет",
                                  f(r["после_дисконта_млн_usd"], 0),
                                  f(r["вес"] * 100, 0) + "%", f(r["вклад_млн_usd"], 1)))
    w("Стоимость входа (pre-money);;;;;;%s" % f(tri["pre_money_млн_usd"], 0))
    w("Стоимость входа, млрд руб;;;;;;%s" % f(tri["pre_money_млрд_руб"]))
    w(";;;;;;;")

    w("Структура раунда;Pre-money_млн_USD;%s;Раунд_млн_USD;%s;Post-money_млн_USD;%s;Доля_инвестора"
      % (f(deal["pre_money_млн_usd"], 0), f(deal["раунд_млн_usd"], 0), f(deal["post_money_млн_usd"], 0)))
    w(";;;;;;;%s" % (f(deal["доля_инвестора"] * 100, 2) + "%"))
    w(";;;;;;;")

    w("Сценарии;Сценарий;Доля рынка год 10;Вес;Стоимость бизнеса_млрд_руб;Выручка год 10_млрд_руб")
    for k in ["Консервативный", "Базовый", "Оптимистичный"]:
        m = scen[k]
        w(";%s;%s;%s;%s;%s" % (k, f(a["сценарии"][k]["доля_год10"] * 100, 0) + "%",
                               f(a["сценарии"][k]["вес"] * 100, 0) + "%",
                               f(m["EV"] / 1000), f(m["выручка"][-1] / 1000)))
    w("Ожидаемое значение;;;;%s;" % f(sum(a["сценарии"][k]["вес"] * scen[k]["EV"] for k in scen) / 1000))
    w(";;;;;;;")

    w("Имитационное моделирование;Итераций;%d;Зерно;%d;;;" % (mc["итераций"], mc["зерно"]))
    for k, lbl in [("P5", "P5"), ("P10", "P10"), ("P25", "P25"), ("медиана", "Медиана"),
                   ("P75", "P75"), ("P90", "P90"), ("P95", "P95")]:
        w(";%s;%s;млрд руб;;;;" % (lbl, f(mc[k] / 1000, 1)))
    w(";Вероятность стоимости выше 50 млрд руб;%s;;;;;" % (f(mc["доля_выше_50млрд"] * 100, 1) + "%"))
    w(";Вероятность отрицательной стоимости;%s;;;;;" % (f(mc["доля_ниже_нуля"] * 100, 1) + "%"))

    io.open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    sys.stdout.write("Записано: %s\n" % OUT)


if __name__ == "__main__":
    main()
