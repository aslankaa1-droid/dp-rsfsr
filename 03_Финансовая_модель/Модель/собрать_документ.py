def n(x, d=0):
    """Число в русском формате с неразрывными разделителями тысяч."""
    if x is None:
        return "—"
    s = "%.*f" % (d, x)
    neg = s.startswith("-")
    s = s.lstrip("-")
    if "." in s:
        ip, fp = s.split(".")
    else:
        ip, fp = s, ""
    out = ""
    while len(ip) > 3:
        out = " " + ip[-3:] + out
        ip = ip[:-3]
    out = ip + out
    if fp:
        out += "," + fp
    return ("−" if neg else "") + out


def dt(s):
    """2026-04-24 -> 24.04.2026"""
    try:
        y, m, d = s.split("-")
        return "%s.%s.%s" % (d, m, y)
    except Exception:
        return s


def pct(x, d=1):
    return "—" if x is None else ("%.*f" % (d, x * 100)).replace(".", ",") + "%"


def row(cells):
    return "| " + " | ".join(str(c) for c in cells) + " |"


def head(cols, align):
    return row(cols) + "\n" + row(align)


def series_table(years, rows, unit_col="Показатель"):
    out = [head([unit_col] + [str(y) for y in years],
                ["---"] + ["---:"] * len(years))]
    for name, vals, d in rows:
        out.append(row([name] + [n(v, d) if not isinstance(v, str) else v for v in vals]))
    return "\n".join(out)


